                    "        num_classes = 10\n",
                    "    elif dataset_name.lower() in [\"stl10\", \"stl-10\"]:\n",
                    "        train_set = torchvision.datasets.STL10(root=data_dir, split=\"train\", download=True, transform=train_transform)\n",
                    "        val_set   = torchvision.datasets.STL10(root=data_dir, split=\"test\", download=True, transform=val_transform)\n",
                    "        num_classes = 10\n",
                    "    else:\n",
                    "        raise ValueError(f\"Unsupported dataset: {dataset_name}\")\n",
                    "    train_loader = DataLoader(train_set, batch_size=batch_size, shuffle=True, num_workers=num_workers, pin_memory=True, drop_last=True)\n",
                    "    val_loader   = DataLoader(val_set, batch_size=batch_size, shuffle=False, num_workers=num_workers, pin_memory=True)\n",
